#!/usr/bin/env node
/**
 * Compiles the host-independent rules of redirects.config.json into public/_redirects, the file
 * Cloudflare Workers Static Assets uses to answer redirects before any asset or Worker code runs.
 *
 * Host-scoped rules are intentionally skipped: _redirects cannot match on hostname, so they are
 * handled by the Worker in workers/legacy-redirects.
 *
 * Usage:
 *   node scripts/generate-cloudflare-redirects.mjs           # write public/_redirects
 *   node scripts/generate-cloudflare-redirects.mjs --check    # fail if the file is out of date
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CONFIG_PATH = join(ROOT, 'redirects.config.json');
const OUTPUT_PATH = join(ROOT, 'public', '_redirects');

/** Cloudflare rejects files with more than these many rules. */
const MAX_STATIC_RULES = 2000;
const MAX_DYNAMIC_RULES = 100;

const isDynamic = (from) => from.includes('*') || from.includes(':');

function renderRule({ from, to, status }) {
  if (!from.startsWith('/')) throw new Error(`Rule source must start with "/": ${from}`);
  if (/\s/.test(from) || /\s/.test(to)) throw new Error(`Rule contains whitespace: ${from} ${to}`);
  return `${from} ${to} ${status}`;
}

async function main() {
  const check = process.argv.includes('--check');
  const { rules } = JSON.parse(await readFile(CONFIG_PATH, 'utf-8'));
  const pathRules = rules.filter((rule) => !rule.host);

  const dynamicCount = pathRules.filter((rule) => isDynamic(rule.from)).length;
  const staticCount = pathRules.length - dynamicCount;
  if (dynamicCount > MAX_DYNAMIC_RULES) {
    throw new Error(`${dynamicCount} dynamic rules exceeds the Cloudflare limit of ${MAX_DYNAMIC_RULES}`);
  }
  if (staticCount > MAX_STATIC_RULES) {
    throw new Error(`${staticCount} static rules exceeds the Cloudflare limit of ${MAX_STATIC_RULES}`);
  }

  const content = [
    '# Generated by scripts/generate-cloudflare-redirects.mjs — do not edit by hand.',
    '# Edit redirects.config.json instead, then run `npm run cf:redirects`.',
    ...pathRules.map(renderRule),
    ''
  ].join('\n');

  const current = await readFile(OUTPUT_PATH, 'utf-8').catch(() => null);
  if (check) {
    if (current !== content) {
      throw new Error('public/_redirects is out of date — run `npm run cf:redirects`');
    }
    console.log(`public/_redirects is up to date (${pathRules.length} rules).`);
    return;
  }

  if (current !== content) await writeFile(OUTPUT_PATH, content, 'utf-8');
  console.log(
    `Wrote public/_redirects: ${pathRules.length} rules (${staticCount} static, ${dynamicCount} dynamic).`
  );
}

main().catch((error) => {
  console.error(`[generate-cloudflare-redirects] ${error.message}`);
  process.exit(1);
});
